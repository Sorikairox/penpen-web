"""Write port/runtime/hle_names.h (address + our SDK name per target the game calls) from sdk_calls.tsv,
plus the SDK functions of port/symbols/hle_extra.tsv (S4: called by SDK code that runs as guest code);
sorted by address (hle.c binary-searches the table)."""
import os
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
rows = []
for fn in ('sdk_calls.tsv', 'hle_extra.tsv'):
    for line in open(os.path.join(R, 'port/symbols', fn)):
        if line.startswith('#'):
            continue
        f = line.split('\t')
        if f[2] == 'data':
            continue
        rows.append((int(f[0], 16), f[1], f[2]))
rows.sort()
out = ['/* generated by tools/s3_hle_names.py from port/symbols/sdk_calls.tsv + hle_extra.tsv */']
out += ['HLE_NAME(0x%08xu, %s, %s)' % r for r in rows]
open(os.path.join(R, 'port/runtime/hle_names.h'), 'w').write('\n'.join(out) + '\n')
print(len(rows))
