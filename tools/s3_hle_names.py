"""Write port/runtime/hle_names.h (address + our SDK name per target the game calls) from sdk_calls.tsv."""
import os
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
out = ['/* generated by tools/s3_hle_names.py from port/symbols/sdk_calls.tsv: the SDK functions the game calls */']
for line in open(os.path.join(R, 'port/symbols/sdk_calls.tsv')):
    if line.startswith('#'):
        continue
    f = line.split('\t')
    if f[2] == 'data':
        continue
    out.append('HLE_NAME(0x%su, %s, %s)' % (f[0], f[1], f[2]))
open(os.path.join(R, 'port/runtime/hle_names.h'), 'w').write('\n'.join(out) + '\n')
print(len(out) - 1)
